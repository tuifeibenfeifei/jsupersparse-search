# -*- coding: utf-8 -*-
"""build_drift_oracle.py - search-and-rescue backward-drift two-stage oracle construction (physical simulation)

[Important note] This oracle is a **physical simulation** and does not use real ocean-current/wind/drift-observation data.
Drift trajectories are constructed by numerically integrating the 2D leeway advection equation dP/dt = C(P) + L_i * W(t),
used to test the SpeciesSearcher framework's "sequential two-stage decoding" pipeline under a fully black-box, 0/1 detection setting.

Scenario (sequential decoding A->B, different space-time, no map fusion):
  Stage A (current space-time, search the drifting-debris snapshot):
    120x120 cells, 2 km per cell (domain 240x240 km). After the shipwreck, 10 debris pieces start from the incident point P0
    and drift with the current for T_A=48 h, each with leeway L_i in [0.01,0.03], sharing the ocean current C and wind W (slowly varying).
    Debris positions are **frozen** at time T_A (snapshot search; queries do not advance time). Detection radius R_A=2 cells
    (=4 km); presence = within R_A of any debris.
  Stage B (past space-time, search the incident point P0):
    Same 120x120 grid; the oracle switches to static evidence of P0 (debris aggregation / oil slick),
    presence = within R_B=3 cells (=6 km) of P0; static and does not change over time.

19 covariates (static per cell, fed to AUC sparse feature selection):
  Physical (7): 0 cur_u / 1 cur_v / 2 wind_u / 3 wind_v /
            4 dist_shore / 5 depth / 6 SAR_prior
  Noise (12): 7..18 smoothed random fields
  At Stage B runtime, a 20th covariate is appended: distance to the "decoded centroid" (generated by the wrapper).

Outputs:
  drift-search/data/stageA.npz  Stage A (debris-snapshot presence + 19 cov + ground truth)
  drift-search/data/stageB.npz  Stage B (P0 static presence + 19 cov + ground truth)
"""
from pathlib import Path

import numpy as np
from scipy import ndimage

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
DATA.mkdir(parents=True, exist_ok=True)

# ---------------- physical parameters (all explicitly recorded; marked as physical simulation) ----------------
N = 120                  # grid 120x120
CELL_KM = 2.0            # 2 km per cell
DOM_KM = N * CELL_KM     # 240 km
R_A_CELL = 2             # Stage A detection radius 2 cells (=4 km)
R_B_CELL = 3             # Stage B detection radius 3 cells (=6 km)
T_A_H = 48.0             # drift duration 48 h
DT_H = 0.5               # integration step size 0.5 h
N_DEBRIS = 10            # number of debris pieces
P0_CELL = (40, 75)       # incident point (cell row i, col j)
LEEWAY_LO, LEEWAY_HI = 0.01, 0.03   # leeway coefficient range per debris
SIM_SEED = 20260930

# incident point in km (cell center)
I0, J0 = P0_CELL
X0 = (J0 + 0.5) * CELL_KM
Y0 = (I0 + 0.5) * CELL_KM


def current_kmh(x, y):
    """Ocean-current field (slowly varying spatial field), returns (cu, cv) km/h."""
    cu = 0.15 + 0.020 * np.sin(y / 40.0)
    cv = 0.03 + 0.015 * np.sin(x / 50.0 + 1.0)
    return cu, cv


def wind_mps(t_h, w_rng):
    """Wind field (slowly varying temporal component + slow noise), returns (wu, wv) m/s.
    The main wind direction is northerly (wv dominant), stretching the leeway spread along the row (i) direction,
    so that a blind-sweep raster passing over that column can hit multiple rows at once."""
    wu = 3.0 + 0.8 * np.sin(2 * np.pi * t_h / 60.0) + 0.2 * w_rng.standard_normal()
    wv = 6.0 + 1.2 * np.sin(2 * np.pi * t_h / 80.0 + 0.5) + 0.3 * w_rng.standard_normal()
    return wu, wv


COV_NAMES_19 = [
    "current u (m/s)", "current v (m/s)", "wind u (m/s)", "wind v (m/s)", "distance to shore (km)",
    "water depth (m)", "SAR prior",
    "wave height (m)", "turbidity (NTU)", "fishing intensity", "salinity anomaly", "wave direction (rad)",
    "gust (m/s)", "chlorophyll (mg/m3)", "sea-fog probability", "ship density", "sea-temperature anomaly",
    "turbidity current (m2/s)", "white noise",
]
assert len(COV_NAMES_19) == 19


def smooth_noise(rng, shape, sigma):
    z = rng.standard_normal(shape)
    z = ndimage.gaussian_filter(z, sigma=sigma, mode="wrap")
    z -= z.min()
    z /= (z.max() + 1e-12)
    return z


def main():
    rng = np.random.default_rng(SIM_SEED)
    w_rng = np.random.default_rng(SIM_SEED + 7)

    ii, jj = np.meshgrid(np.arange(N), np.arange(N), indexing="ij")  # ii=row, jj=col
    X = (jj + 0.5) * CELL_KM   # east km
    Y = (ii + 0.5) * CELL_KM   # north km

    # ---- 19 static covariate fields ----
    # 0,1 ocean current u/v (m/s) - same function used for drift integration
    cu_grid, cv_grid = current_kmh(X, Y)
    covs = np.zeros((19, N, N), dtype=np.float32)
    covs[0] = (cu_grid / 3.6).astype(np.float32)
    covs[1] = (cv_grid / 3.6).astype(np.float32)
    # 2,3 wind climate u/v (m/s, large-scale spatial smoothing; distinguished from the slowly varying temporal wind)
    covs[2] = (3.0 + 0.3 * np.sin(Y / 90.0)).astype(np.float32)
    covs[3] = (6.0 + 0.4 * np.sin(X / 100.0 + 0.5)).astype(np.float32)
    # 4 distance to shore (km): to the nearest boundary
    covs[4] = (np.minimum(np.minimum(X, DOM_KM - X),
                          np.minimum(Y, DOM_KM - Y))).astype(np.float32)
    # 5 water depth (m): deepens offshore
    depth = 10.0 + covs[4] * 2.0 + rng.normal(0, 0.5, (N, N))
    covs[5] = depth.astype(np.float32)
    # 7..18 noise pool
    for k in range(7, 19):
        sig = rng.uniform(2.0, 7.0)
        covs[k] = smooth_noise(rng, (N, N), sig).astype(np.float32)

    # ---- drift integration: 10 debris pieces start from P0, 48h ----
    n_steps = int(T_A_H / DT_H)            # 96
    L_vals = np.linspace(LEEWAY_LO, LEEWAY_HI, N_DEBRIS)   # 0.01..0.03, mean 0.02
    # The wind is a shared environmental forcing: precompute one wind time series shared by all debris (only the leeway coefficient differs)
    wind_u_t = np.zeros(n_steps)
    wind_v_t = np.zeros(n_steps)
    for s in range(n_steps):
        t_h = s * DT_H
        wind_u_t[s], wind_v_t[s] = wind_mps(t_h, w_rng)
    wu_mean = float(wind_u_t.mean())
    wv_mean = float(wind_v_t.mean())

    debris_km = np.zeros((N_DEBRIS, 2))     # final state (x,y) km
    diff_rng = np.random.default_rng(SIM_SEED + 13)
    DIFF_KM2H = 0.5     # turbulent diffusion coefficient (km^2/h), random-walk diffusion
    for k in range(N_DEBRIS):
        pos = np.array([X0, Y0], dtype=float)
        for s in range(n_steps):
            cu, cv = current_kmh(pos[0], pos[1])
            wu, wv = wind_u_t[s], wind_v_t[s]
            # leeway speed km/h = L * W(m/s) * 3.6
            lu = L_vals[k] * wu * 3.6
            lv = L_vals[k] * wv * 3.6
            vx = cu + lu
            vy = cv + lv
            # turbulent diffusion: random walk sqrt(2 D dt)
            sg = (2.0 * DIFF_KM2H * DT_H) ** 0.5
            pos = pos + np.array([vx, vy]) * DT_H + sg * diff_rng.standard_normal(2)
        debris_km[k] = pos

    # representative decoded drift (for wrapper inversion): currently uses the current at P0 + time-averaged wind + mean leeway 0.02
    cu_p0, cv_p0 = current_kmh(X0, Y0)
    L_hat = 0.5 * (LEEWAY_LO + LEEWAY_HI)   # 0.02
    disp_dec = np.array([cu_p0 + L_hat * wu_mean * 3.6,
                         cv_p0 + L_hat * wv_mean * 3.6]) * T_A_H   # km
    cloud_center_km = np.array([X0, Y0]) + disp_dec          # expected debris-cloud center

    # SAR prior: centered on "P0 + drift estimate", large sigma (=30 km)
    SIGMA_SAR_KM = 30.0
    sar_prior = np.exp(-((X - cloud_center_km[0]) ** 2 +
                         (Y - cloud_center_km[1]) ** 2) /
                       (2.0 * SIGMA_SAR_KM ** 2))
    covs[6] = sar_prior.astype(np.float32)

    # ---- Stage A presence: within R_A_CELL cells of any debris ----
    presenceA = np.zeros((N, N), dtype=bool)
    debris_cell = np.zeros((N_DEBRIS, 2), dtype=int)
    for k in range(N_DEBRIS):
        dc = int(round(debris_km[k][1] / CELL_KM - 0.5))   # row i ~ y
        dr = int(round(debris_km[k][0] / CELL_KM - 0.5))   # col j ~ x
        debris_cell[k] = (dc, dr)
        for di in range(-R_A_CELL, R_A_CELL + 1):
            for dj in range(-R_A_CELL, R_A_CELL + 1):
                if di * di + dj * dj > R_A_CELL * R_A_CELL:
                    continue
                ii_, jj_ = dc + di, dr + dj
                if 0 <= ii_ < N and 0 <= jj_ < N:
                    presenceA[ii_, jj_] = True

    # ---- Stage B presence: within R_B_CELL cells of P0 ----
    presenceB = np.zeros((N, N), dtype=bool)
    for di in range(-R_B_CELL, R_B_CELL + 1):
        for dj in range(-R_B_CELL, R_B_CELL + 1):
            if di * di + dj * dj > R_B_CELL * R_B_CELL:
                continue
            ii_, jj_ = I0 + di, J0 + dj
            if 0 <= ii_ < N and 0 <= jj_ < N:
                presenceB[ii_, jj_] = True

    # ---- self-check ----
    disp = np.hypot(debris_km[:, 0] - X0, debris_km[:, 1] - Y0)
    print(f"[build] P0=({X0:.1f},{Y0:.1f}) km  domain=[0,{DOM_KM}]km")
    print(f"[build] debris final displacement from P0: min={disp.min():.1f} max={disp.max():.1f} "
          f"mean={disp.mean():.1f} km")
    print(f"[build] expected debris-cloud center=({cloud_center_km[0]:.1f},{cloud_center_km[1]:.1f}) km")
    print(f"[build] decoded representative displacement=({disp_dec[0]:.2f},{disp_dec[1]:.2f}) km "
          f"(cu_p0={cu_p0:.3f} cv_p0={cv_p0:.3f} wu_mean={wu_mean:.2f} wv_mean={wv_mean:.2f})")
    print(f"[build] Stage A presence cells={int(presenceA.sum())} "
          f"({presenceA.mean()*100:.2f}%)")
    print(f"[build] Stage B presence cells={int(presenceB.sum())} "
          f"({presenceB.mean()*100:.2f}%)")

    metaA = ("PHYSICS_SIMULATION_NOT_REAL_DATA | leeway drift snapshot (frozen at T_A=48h); "
             "dP/dt=C(P)+L_i*W(t); 0/1 detection within R_A=2 cells=4km of any debris; "
             "static snapshot, query does NOT advance time.")
    metaB = ("PHYSICS_SIMULATION_NOT_REAL_DATA | static wreck-point evidence (debris "
             "aggregation/oil slick); presence within R_B=3 cells=6km of P0; static.")

    # ---- save stageA.npz ----
    np.savez(
        DATA / "stageA.npz",
        covs=covs.astype(np.float32),
        presence=presenceA,
        cov_names=np.array(COV_NAMES_19),
        nrows=N, ncols=N, cell_km=CELL_KM,
        # ground truth (for reporting/decoding only, invisible to black-box search)
        P0_i=I0, P0_j=J0, P0_x=X0, P0_y=Y0,
        debris_cell=debris_cell.astype(np.int32),     # (10,2) row,col
        debris_km=debris_km.astype(np.float64),       # (10,2) x,y
        R_A_cell=R_A_CELL, R_B_cell=R_B_CELL,
        T_A_h=T_A_H, dt_h=DT_H, n_debris=N_DEBRIS,
        leeway_lo=LEEWAY_LO, leeway_hi=LEEWAY_HI, leeway_hat=L_hat,
        # decoded wrapper representative quantities
        cu_p0=cu_p0, cv_p0=cv_p0, wu_mean=wu_mean, wv_mean=wv_mean,
        cloud_center_x=cloud_center_km[0], cloud_center_y=cloud_center_km[1],
        sim_seed=SIM_SEED,
        meta=metaA,
    )
    # ---- save stageB.npz (same 19 cov, presence switched to P0 static evidence) ----
    np.savez(
        DATA / "stageB.npz",
        covs=covs.astype(np.float32),
        presence=presenceB,
        cov_names=np.array(COV_NAMES_19),
        nrows=N, ncols=N, cell_km=CELL_KM,
        P0_i=I0, P0_j=J0, P0_x=X0, P0_y=Y0,
        R_B_cell=R_B_CELL,
        sim_seed=SIM_SEED,
        meta=metaB,
    )
    print(f"[build] -> {DATA/'stageA.npz'}  covs={covs.shape}")
    print(f"[build] -> {DATA/'stageB.npz'}")


if __name__ == "__main__":
    main()

